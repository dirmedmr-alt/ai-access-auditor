#!/usr/bin/env node
// Builds site/fr/index.html and site/ar/index.html from site/index.html (the English source) and the
// translations in i18n/site.js. Never edit the generated pages by hand: change the source and run this again.
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const T = require('./site.js');
const src = fs.readFileSync(path.join(root, 'site', 'index.html'), 'utf8');
const ZH = new Map(require('./site-zh.js'));
const LANGS = [['fr', 1], ['ar', 2], ['zh', 'zh']];

// every English text must still be in the page, or a translation would silently go missing
const missing = T.filter(r => !src.includes(r[0]));
const dupes = T.map(r => r[0]).filter((k, i, a) => a.indexOf(k) !== i);
if (missing.length || dupes.length) {
  if (missing.length) console.error('These English texts are no longer in site/index.html. Update i18n/site.js:\n' + missing.map(r => '  - ' + r[0].slice(0, 100)).join('\n'));
  if (dupes.length) console.error('Listed twice in i18n/site.js:\n' + dupes.map(k => '  - ' + k.slice(0, 100)).join('\n'));
  process.exit(1);
}
const noZh = T.filter(r => !ZH.has(r[0]));
if (noZh.length) { console.error('These texts have no Chinese in i18n/site-zh.js:\n' + noZh.map(r => '  - ' + r[0].slice(0, 100)).join('\n')); process.exit(1); }

// one pass, longest text first, so a translated sentence is never translated again
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const re = new RegExp(T.map(r => r[0]).sort((a, b) => b.length - a.length).map(esc).join('|'), 'g');

for (const [lang, col] of LANGS) {
  const map = new Map(T.map(r => [r[0], col === 'zh' ? ZH.get(r[0]) : r[col]]));
  let out = src.replace(re, m => map.get(m))
    .replace('<html lang="en">', lang === 'ar' ? '<html lang="ar" dir="rtl">' : `<html lang="${lang}">`)
    .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by i18n/build-site.js from site/index.html and i18n/site.js. Do not edit by hand. -->')
    .replace(/(src|href|poster)="assets\//g, '$1="../assets/')
    .replace(/href="(fr|ar|zh)\/"/g, 'href="../$1/"')
    .replace(/href="\.\/"/g, 'href="../"')
    .replace(/ aria-current="page"/g, '');
  // keep "1.0.2 beta · 71 MB" in its own order inside Arabic text
  if (lang === 'ar') out = out.replace(/الإصدار ([0-9][^<]*)<\/span>/g, 'الإصدار <bdi dir="ltr">$1</bdi></span>');
  const here = `href="../${lang}/" hreflang="${lang}"`;
  if (!out.includes(here)) { console.error(`Language switch link for ${lang} not found.`); process.exit(1); }
  out = out.replace(here, `${here} aria-current="page"`);
  const dir = path.join(root, 'site', lang);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), out);
  console.log(`site/${lang}/index.html: ${T.length} texts translated`);
}
